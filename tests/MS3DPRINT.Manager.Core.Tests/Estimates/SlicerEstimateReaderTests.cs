using System.IO.Compression;
using System.Text;
using MS3DPRINT.Manager.Core.Estimates;

namespace MS3DPRINT.Manager.Core.Tests.Estimates;

public sealed class SlicerEstimateReaderTests : IDisposable
{
    private readonly string _root = Directory.CreateTempSubdirectory("slicer-estimate-").FullName;
    public void Dispose() => Directory.Delete(_root, true);

    private string Write(string name, string text) { var path = Path.Combine(_root, name); File.WriteAllText(path, text); return path; }

    [Theory]
    [InlineData("; HEADER_BLOCK_START\r\n; BambuStudio 02.02.00.85\r\n; model printing time: 1h 2m 3s; total estimated time: 1h 10m 31s\r\n; total filament weight [g] : 25.61\r\n; HEADER_BLOCK_END\r\nG28\r\n", 25.61, 71)]
    [InlineData("; generated by OrcaSlicer 2.3.0\n; total filament used [g] = 12.5\n; estimated printing time (normal mode) = 2d 1h 0m 30s\nG1 X0\n", 12.5, 2941)]
    [InlineData("G28\nG1 X10\n; filament used [mm] = 1000\n; filament used [g] = 10.25, 2.75\n; estimated printing time (normal mode) = 45m 29s\n", 13, 45)]
    public void Reads_weight_and_time_from_gcode(string gcode, double grams, int minutes)
    {
        var estimate = SlicerEstimateReader.Read(Write("part.gcode", gcode));
        Assert.NotNull(estimate);
        Assert.Equal((decimal)grams, estimate.Grams);
        Assert.Equal(minutes, estimate.Minutes);
        Assert.Equal(1, estimate.Plates);
    }

    [Fact]
    public void Cura_length_is_converted_to_pla_weight()
    {
        var estimate = SlicerEstimateReader.Read(Write("cura.gcode", ";FLAVOR:Marlin\r\n;TIME:123600\r\n;Filament used: 94.001m\r\n;Layer height: 0.2\r\n;Generated with Cura_SteamEngine 5.10.2\r\nG28\r\n"));
        Assert.NotNull(estimate);
        Assert.True(estimate.FromLength);
        Assert.Equal(2060, estimate.Minutes);
        Assert.InRange(estimate.Grams, 280m, 281m);
    }

    [Fact]
    public void Prusa_summary_at_the_end_of_a_large_file_is_found()
    {
        var text = new StringBuilder("; PrusaSlicer\n");
        while (text.Length < 3 * 1024 * 1024) text.Append("G1 X10.123 Y20.456 E0.0123\n");
        text.Append("; filament used [g] = 8.4\n; estimated printing time (normal mode) = 1h 0m 0s\n");
        var estimate = SlicerEstimateReader.Read(Write("large.gcode", text.ToString()));
        Assert.Equal(new SlicerEstimate(8.4m, 60, 1), estimate);
    }

    [Fact]
    public void Sliced_3mf_adds_every_plate_and_a_project_without_slicing_has_no_estimate()
    {
        var sliced = Path.Combine(_root, "plates.gcode.3mf");
        using (var zip = ZipFile.Open(sliced, ZipArchiveMode.Create))
        using (var writer = new StreamWriter(zip.CreateEntry("Metadata/slice_info.config").Open()))
            writer.Write("<config><plate><metadata key=\"index\" value=\"1\"/><metadata key=\"prediction\" value=\"3600\"/><metadata key=\"weight\" value=\"20.50\"/></plate>"
                + "<plate><metadata key=\"index\" value=\"2\"/><metadata key=\"prediction\" value=\"1830\"/><metadata key=\"weight\" value=\"4.25\"/></plate></config>");
        Assert.Equal(new SlicerEstimate(24.75m, 91, 2), SlicerEstimateReader.Read(sliced));

        var platesOnly = Path.Combine(_root, "header.gcode.3mf");
        using (var zip = ZipFile.Open(platesOnly, ZipArchiveMode.Create))
        using (var writer = new StreamWriter(zip.CreateEntry("Metadata/plate_1.gcode").Open()))
            writer.Write("; total estimated time: 30m 0s\n; total filament weight [g] : 6.5\nG28\n");
        Assert.Equal(new SlicerEstimate(6.5m, 30, 1), SlicerEstimateReader.Read(platesOnly));

        var project = Path.Combine(_root, "project.3mf");
        using (var zip = ZipFile.Open(project, ZipArchiveMode.Create))
        using (var writer = new StreamWriter(zip.CreateEntry("3D/3dmodel.model").Open())) writer.Write("<model/>");
        Assert.Null(SlicerEstimateReader.Read(project));
        Assert.Null(SlicerEstimateReader.Read(Write("broken.3mf", "not a zip")));
        Assert.Null(SlicerEstimateReader.Read(Write("model.stl", "solid x")));
    }
}
